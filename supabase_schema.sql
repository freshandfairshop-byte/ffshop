-- ==============================================================================
-- CLOUD INVENTORY & SALES SYSTEM: POSTGRESQL SCHEMA (SUPABASE)
-- Currency: Bangladeshi Taka (৳ BDT)
-- Run this script inside Supabase Dashboard -> SQL Editor
-- ==============================================================================

-- 1. Create the Inventory Table
-- Customer info is strictly in Sales. Inventory tracks catalog, shipments, and landed costs.
CREATE TABLE IF NOT EXISTS inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name TEXT NOT NULL,
    stock_level INTEGER NOT NULL DEFAULT 0 CHECK (stock_level >= 0),
    price DECIMAL(12, 2) NOT NULL DEFAULT 0.00 CHECK (price >= 0), -- Selling price in ৳ BDT (manual or suggested)
    shipment_code TEXT DEFAULT 'SHP-2026-01', -- Inbound shipment code
    buying_price DECIMAL(12, 2) DEFAULT 0.00 CHECK (buying_price >= 0), -- Base purchase price in ৳ BDT
    transport_cost DECIMAL(12, 2) DEFAULT 0.00 CHECK (transport_cost >= 0), -- Total shipment transport cost in ৳ BDT
    handling_cost DECIMAL(12, 2) DEFAULT 0.00 CHECK (handling_cost >= 0), -- Other handling cost in ৳ BDT
    dispersed_transport DECIMAL(12, 2) DEFAULT 0.00 CHECK (dispersed_transport >= 0), -- Transport equally dispersed across items
    total_buying_cost DECIMAL(12, 2) DEFAULT 0.00 CHECK (total_buying_cost >= 0), -- Effective landed buying cost
    suggested_price DECIMAL(12, 2) DEFAULT 0.00 CHECK (suggested_price >= 0), -- 5% profit suggested selling price
    category TEXT DEFAULT 'General',
    sku TEXT,
    updated_by TEXT NOT NULL,
    last_updated TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_inventory_item_name ON inventory(item_name);
CREATE INDEX IF NOT EXISTS idx_inventory_shipment_code ON inventory(shipment_code);

-- 2. Create the Sales Table (Customer information is ONLY stored in the Sales window)
-- Note on Multiple Shipments & Transport: Each sale/shipment record has its own distinct transport_cost (৳ BDT)
CREATE TABLE IF NOT EXISTS sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES inventory(id) ON DELETE RESTRICT,
    quantity_sold INTEGER NOT NULL CHECK (quantity_sold > 0),
    unit_price DECIMAL(12, 2) NOT NULL DEFAULT 0.00 CHECK (unit_price >= 0), -- Unit price in ৳ BDT
    subtotal_amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00 CHECK (subtotal_amount >= 0), -- quantity * unit_price
    transport_cost DECIMAL(12, 2) NOT NULL DEFAULT 0.00 CHECK (transport_cost >= 0), -- Outbound shipping / courier fee (calculated separately per shipment in ৳ BDT)
    discount_amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00 CHECK (discount_amount >= 0), -- Discount in ৳ BDT
    total_amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00 CHECK (total_amount >= 0), -- (subtotal + transport_cost - discount) in ৳ BDT
    customer_name TEXT NOT NULL DEFAULT 'Walk-in Customer',
    customer_address TEXT NOT NULL DEFAULT 'In-store Purchase',
    customer_phone TEXT NOT NULL DEFAULT '01700-000000',
    sale_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    processed_by TEXT NOT NULL,
    receipt_number TEXT
);

CREATE INDEX IF NOT EXISTS idx_sales_sale_date ON sales(sale_date DESC);
CREATE INDEX IF NOT EXISTS idx_sales_item_id ON sales(item_id);
CREATE INDEX IF NOT EXISTS idx_sales_customer_phone ON sales(customer_phone);
CREATE INDEX IF NOT EXISTS idx_sales_customer_name ON sales(customer_name);

-- 3. Enable Row Level Security (RLS)
ALTER TABLE inventory ENABLE ROW LEVEL SECURITY;
ALTER TABLE sales ENABLE ROW LEVEL SECURITY;

-- 4. Create RLS Policies for Authenticated Application Users
CREATE POLICY "Allow authenticated full access to inventory"
    ON inventory
    FOR ALL
    TO authenticated
    USING (true)
    WITH CHECK (true);

CREATE POLICY "Allow authenticated full access to sales"
    ON sales
    FOR ALL
    TO authenticated
    USING (true)
    WITH CHECK (true);

-- Also allow public anon access for demo prototyping (can be restricted in production)
CREATE POLICY "Allow public anon access for inventory prototype"
    ON inventory
    FOR ALL
    TO anon
    USING (true)
    WITH CHECK (true);

CREATE POLICY "Allow public anon access for sales prototype"
    ON sales
    FOR ALL
    TO anon
    USING (true)
    WITH CHECK (true);
